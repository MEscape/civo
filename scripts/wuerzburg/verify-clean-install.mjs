import 'dotenv/config';

import { execFile } from 'node:child_process';
import { randomUUID } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import process from 'node:process';
import { fileURLToPath, URL } from 'node:url';
import { promisify } from 'node:util';

import { Pool } from 'pg';

const ROOT = fileURLToPath(new URL('../../', import.meta.url));
const execute = promisify(execFile);
const REPORT = new URL('../../docs/würzburg/verification/clean-install.json', import.meta.url);
const IDEMPOTENCY = new URL(
  '../../docs/würzburg/verification/seed-idempotency.json',
  import.meta.url,
);
const suffix = randomUUID().replaceAll('-', '');
const created = [];
const steps = [];
const cleanup = [];
let savedIdempotency;
let failedStage = null;

if (process.env.NODE_ENV === 'production') throw new Error('Development verification only');

function localTarget(key, role) {
  const value = process.env[key];
  if (!value) throw new Error('Both local database URLs are required');
  const original = new URL(value);
  if (
    !['localhost', '127.0.0.1', '[::1]'].includes(original.hostname) ||
    !['postgres:', 'postgresql:'].includes(original.protocol)
  )
    throw new Error('Clean-install verification only supports explicitly local Postgres');
  const name = `civo_wue_verify_${role}_${suffix}`;
  const target = new URL(original);
  target.pathname = `/${name}`;
  return {
    key,
    name,
    target: target.toString(),
    admin: new Pool({ connectionString: value, connectionTimeoutMillis: 5000 }),
  };
}

const targets = [localTarget('DATABASE_URL', 'app'), localTarget('AUTH_DATABASE_URL', 'auth')];
const environment = {
  ...process.env,
  ...Object.fromEntries(targets.map((target) => [target.key, target.target])),
};

async function run(label, args) {
  failedStage = label;
  await execute(process.execPath, args, {
    cwd: ROOT,
    env: environment,
    timeout: 180000,
    maxBuffer: 1024 * 1024,
  });
  steps.push({ label, passed: true });
  process.stdout.write(`${label}: passed\n`);
}

try {
  for (const target of targets) {
    // Only names generated by this invocation enter DDL; configured database names never do.
    if (!/^civo_wue_verify_(app|auth)_[a-f0-9]{32}$/.test(target.name))
      throw new Error('Unsafe verification database identifier');
    failedStage = `create isolated ${target.key}`;
    await target.admin.query(`CREATE DATABASE "${target.name}"`);
    created.push(target);
  }
  try {
    savedIdempotency = await readFile(IDEMPOTENCY);
  } catch {
    throw new Error('Run existing-database seed verification before the isolated check');
  }
  await run('application migrations from empty', [
    'node_modules/prisma/dist/prisma.js',
    'db',
    'migrate',
  ]);
  await run('auth migrations from empty', [
    'node_modules/tsx/dist/cli.mjs',
    'migrations/apply-auth-migration.ts',
  ]);
  await run('strict schema verification', [
    'node_modules/prisma/dist/prisma.js',
    'db',
    'verify',
    '--strict',
  ]);
  await run('clean seed and repeated-seed digests', [
    'node_modules/tsx/dist/cli.mjs',
    '--import',
    './scripts/lib/server-runtime.ts',
    'scripts/wuerzburg/verify-seed.ts',
  ]);
  const idempotency = JSON.parse(await readFile(IDEMPOTENCY, 'utf8'));
  if (idempotency.passed !== true || idempotency.after.Website.count !== 1)
    throw new Error('Isolated seed verification failed');
  await writeFile(
    new URL('../../docs/würzburg/verification/clean-install-idempotency.json', import.meta.url),
    JSON.stringify(
      {
        ...idempotency,
        scope: 'New isolated local application/auth databases; removed after verification',
      },
      null,
      2,
    ) + '\n',
  );
  failedStage = null;
} catch {
  process.exitCode = 1;
  process.stderr.write(
    `Clean installation failed at: ${failedStage ?? 'verification setup'}. Credentials and child-process output withheld.\n`,
  );
} finally {
  if (savedIdempotency !== undefined) await writeFile(IDEMPOTENCY, savedIdempotency);
  for (const target of created.reverse()) {
    // Cleanup is limited to successful CREATEs owned by this exact invocation; never force-disconnect other clients.
    if (
      !target.name.endsWith(suffix) ||
      !/^civo_wue_verify_(app|auth)_[a-f0-9]{32}$/.test(target.name)
    ) {
      cleanup.push({ database: target.name, removed: false });
      process.exitCode = 1;
      continue;
    }
    try {
      await target.admin.query(`DROP DATABASE "${target.name}"`);
      cleanup.push({ database: target.name, removed: true });
    } catch {
      cleanup.push({ database: target.name, removed: false });
      process.exitCode = 1;
    }
  }
  await Promise.all(targets.map((target) => target.admin.end()));
  await writeFile(
    REPORT,
    JSON.stringify(
      {
        capturedAt: new Date().toISOString(),
        passed: process.exitCode !== 1 && failedStage === null,
        failedStage,
        steps,
        cleanup,
        limitation:
          'Fresh local migration/seed only; no production deployment, migration down, reset, or runtime performance verified. Existing databases were not migrated, seeded, or dropped by this check.',
      },
      null,
      2,
    ) + '\n',
  );
}
