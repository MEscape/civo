import { readFile, writeFile } from 'node:fs/promises';
import { URL } from 'node:url';

const root = new URL('../../', import.meta.url);
const manifest = JSON.parse(await readFile(new URL('data/seeds/wuerzburg.json', root), 'utf8'));
const catalog = JSON.parse(
  await readFile(
    new URL('src/modules/component-platform/domain/components/component-versions.lock.json', root),
    'utf8',
  ),
);
const coverage = new Map(Object.keys(catalog).map((type) => [type, []]));
const datasetNames = new Map(manifest.datasets.map((dataset) => [dataset.id, dataset.name]));

function visit(node, page) {
  const bindings = Object.entries(node.props ?? {})
    .filter(([key]) => key.endsWith('DatasetId') || key === 'datasetId')
    .map(([, value]) => datasetNames.get(value))
    .filter(Boolean);
  coverage.get(node.type)?.push({ page: page.path || '/', bindings });
  for (const child of node.children ?? []) visit(child, page);
}
for (const page of manifest.pages.filter((item) => item.path !== 'component-lab'))
  visit(page.config, page);
const rows = [...coverage].map(([type, occurrences]) => {
  const examples = [...new Set(occurrences.map((item) => item.page))];
  const data = [...new Set(occurrences.flatMap((item) => item.bindings))];
  return `| ${type} | ${catalog[type].version} | ${examples.map((item) => '`' + item + '`').join(', ')} | ${data.join('; ') || (type === 'booking' ? 'Official appointments; local booking fixtures stay internal' : 'Editorial layout and verified service links')} |`;
});
const missing = [...coverage]
  .filter(([, occurrences]) => occurrences.length === 0)
  .map(([type]) => type);
const text = `# Published component coverage

Generated by \`node scripts/wuerzburg/coverage.mjs\` from the current seed manifest and version lock.
The public site uses components only where real data and citizen tasks justify them. The user replaced the original public catalog-showcase requirement.
There are ${manifest.pages.length} stored pages; Component Lab is a draft excluded from the public release. It remains accessible through the protected builder.

| Component | Version | Published page paths | Data or civic use case |
| --- | --- | --- | --- |
${rows.join('\n')}

Not needed on current public pages: ${missing.length ? missing.join(', ') : 'none'}.

## Limits

- Maps draw first-party vectors from real district polygons and located records, with a list alternative. Advanced tile/heatmap/cluster coverage is not claimed.
- All ${manifest.datasets.length} configured datasets contain real source snapshots; some are retained only for internal contract review. A bounded refresh command and separate worker are implemented. Deployment scheduling must be configured and monitored by the operator.
- Standalone catalog and map pages were removed. Metadata for 185 catalog entries stays in the evidence register.
- Lab content is representative, not an exhaustive loading/stale/error/empty/brand state matrix.
- No global full-text search, official legal approval, transit connection, choropleth, route/WMS/time-slider suite, or waitlist is claimed.
`;
await writeFile(new URL('docs/würzburg/03-component-coverage.md', root), text);
