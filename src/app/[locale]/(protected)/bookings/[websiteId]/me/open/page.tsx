import { Suspense } from 'react';

import type { Metadata } from 'next';

import { OpenBookingsAdministration } from '@modules/booking';

import { BookingPageSkeleton } from '@components/skeletons/booking-page-skeleton';

import { requireLocale } from '@i18n';

import { getTranslations } from '@i18n/server';

import { buildPrivateMetadata } from '@lib/seo';

import { getWebsiteAccess } from '@/app/_lib/website-access';

interface RouteProps {
  readonly params: Promise<{ locale: string; websiteId: string }>;
  readonly searchParams: Promise<Record<string, string | string[] | undefined>>;
}

export async function generateMetadata({ params }: RouteProps): Promise<Metadata> {
  const locale = requireLocale((await params).locale);
  const t = await getTranslations({ locale, namespace: 'booking' });
  return buildPrivateMetadata(t('employee.open.title'));
}

async function OpenBookingsContent({ params, searchParams }: RouteProps) {
  const { locale: rawLocale, websiteId } = await params;
  const access = await getWebsiteAccess();
  return (
    <OpenBookingsAdministration
      locale={requireLocale(rawLocale)}
      websiteId={websiteId}
      searchParams={await searchParams}
      may={access.may}
    />
  );
}

export default function OpenBookingsPage(props: RouteProps) {
  return (
    <Suspense fallback={<BookingPageSkeleton variant="open" hasAlert />}>
      <OpenBookingsContent {...props} />
    </Suspense>
  );
}
